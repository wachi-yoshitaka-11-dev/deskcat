#!/usr/bin/env python3
"""Extract the #23 local speech characters from the official k8x12 BDF archive.

Run from the repository root:
  python3 scripts/generate_speech_glyphs.py /path/to/k8x12_bdf_2021-05-05.zip
  python3 scripts/generate_speech_glyphs.py /path/to/k8x12_bdf_2021-05-05.zip --check

Source: https://littlelimit.net/k8x12.htm (2021-05-05, k8x12.bdf)
License: https://littlelimit.net/font.htm#%E3%83%A9%E3%82%A4%E3%82%BB%E3%83%B3%E3%82%B9
Copyright (C) 2015-2021 Num Kadoma.
"""

import argparse
import hashlib
import re
from pathlib import Path
from zipfile import ZipFile


ARCHIVE_SHA256 = "305ab94915ec3c8e1ada08f493ee5bfdd21e2710a97d7c4d4272444d8e18ff40"
SOURCE = Path("crates/deskcat-domain/src/local_speech.rs")
OUTPUT = Path("crates/deskcat-face/src/speech_glyphs.rs")
FONT_ASCENT = 10
GLYPH_WIDTH = 8
GLYPH_HEIGHT = 12


def needed_chars() -> list[str]:
    source = SOURCE.read_text(encoding="utf-8")
    match = re.search(r"pub const LOCAL_SPEECH_LINES:.*?= &\[(.*?)\];", source, re.S)
    if match is None:
        raise ValueError(f"LOCAL_SPEECH_LINES not found in {SOURCE}")
    lines = re.findall(r'^\s*"([^"\\]*)",\s*$', match.group(1), re.M)
    if len(lines) != 3:
        raise ValueError("expected the three literal LOCAL_SPEECH_LINES")
    return sorted(set("".join(lines)))


def read_glyphs(bdf: str, chars: list[str]) -> dict[str, list[int]]:
    wanted = {ord(char): char for char in chars}
    result = {}
    for block in bdf.split("STARTCHAR ")[1:]:
        glyph = block.split("ENDCHAR", 1)[0]
        encoding = re.search(r"^ENCODING (\d+)$", glyph, re.M)
        if encoding is None or int(encoding.group(1)) not in wanted:
            continue
        char = wanted[int(encoding.group(1))]
        bounds = re.search(r"^BBX (\d+) (\d+) (-?\d+) (-?\d+)$", glyph, re.M)
        bitmap = re.search(r"^BITMAP\n((?:[0-9A-F]+\n)*)", glyph, re.M)
        if bounds is None or bitmap is None:
            raise ValueError(f"incomplete BDF glyph U+{ord(char):04X}")
        width, height, xoff, yoff = map(int, bounds.groups())
        source_rows = bitmap.group(1).splitlines()
        if len(source_rows) != height:
            raise ValueError(f"invalid BDF height U+{ord(char):04X}")
        rows = [0] * GLYPH_HEIGHT
        for sy, hex_row in enumerate(source_rows):
            bits = int(hex_row, 16)
            padded_width = ((width + 7) // 8) * 8
            for sx in range(width):
                if bits & (1 << (padded_width - sx - 1)):
                    x = xoff + sx
                    y = FONT_ASCENT - yoff - height + sy
                    if not (0 <= x < GLYPH_WIDTH and 0 <= y < GLYPH_HEIGHT):
                        raise ValueError(f"glyph outside 8x12 cell U+{ord(char):04X}")
                    rows[y] |= 0x80 >> x
        if char in result:
            raise ValueError(f"duplicate BDF glyph U+{ord(char):04X}")
        result[char] = rows
    missing = set(chars) - result.keys()
    if missing:
        raise ValueError(f"missing glyphs: {''.join(sorted(missing))}")
    return result


def rust_source(glyphs: dict[str, list[int]]) -> str:
    lines = [
        "// Generated by scripts/generate_speech_glyphs.py from k8x12.bdf 2021-05-05.",
        "// Source archive SHA-256: " + ARCHIVE_SHA256,
        "// Copyright (C) 2015-2021 Num Kadoma. See docs/fonts/k8x12-speech.md.",
        "// One row is one byte; bit 7 is the leftmost pixel of the 8x12 cell.",
        "#[rustfmt::skip]",
        "pub(super) const GLYPHS: &[(char, [u8; 12])] = &[",
    ]
    for char, rows in glyphs.items():
        lines.append(
            f"    ('\\u{{{ord(char):04x}}}', [{', '.join(f'0x{row:02x}' for row in rows)}]), // {char}"
        )
    lines.extend(["];", ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = args.archive.read_bytes()
    if hashlib.sha256(data).hexdigest() != ARCHIVE_SHA256:
        raise ValueError("archive SHA-256 differs from the reviewed official release")
    with ZipFile(args.archive) as archive:
        bdf = archive.read("k8x12.bdf").decode("ascii")
    glyphs = read_glyphs(bdf, needed_chars())
    generated = rust_source(glyphs)
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != generated:
            raise ValueError(f"{OUTPUT} is stale")
    else:
        OUTPUT.write_text(generated, encoding="utf-8")
    print(f"{len(glyphs)} glyphs: {OUTPUT}")


if __name__ == "__main__":
    main()
